import Foundation

/// Replace characters that are illegal in note names with '-'.
public func cleanTitle(_ title: String) -> String {
    String(title.map { "/\\:[]|".contains($0) ? "-" : $0 })
}

public enum Notes {
    public static let dailyNoteTitle = "Today's Meetings.md"

    /// Basenames (without .md) of every note in the vault.
    public static func scanVault(_ vault: URL) -> Set<String> {
        var names = Set<String>()
        let enumerator = FileManager.default.enumerator(
            at: vault, includingPropertiesForKeys: nil, options: [.skipsHiddenFiles])
        while let url = enumerator?.nextObject() as? URL {
            if url.pathExtension == "md" { names.insert(url.deletingPathExtension().lastPathComponent) }
        }
        return names
    }

    /// Sunday noon through Friday 6pm, and never between 7pm and 4am.
    public static func isNoteWindowOpen(_ date: Date, calendar: Calendar = .current) -> Bool {
        let day = calendar.component(.weekday, from: date) - 1  // 0 = Sunday
        let hour = calendar.component(.hour, from: date)
        if day == 6 { return false }
        if day == 0 && hour < 12 { return false }
        if day == 5 && hour >= 18 { return false }
        if hour >= 19 || hour < 4 { return false }
        return true
    }

    public static func render(day: Date, meetings: [Meeting], noteNames: Set<String>,
                              newMeetingsFolder: String, generatedAt: Date) -> String {
        let posix = Locale(identifier: "en_US_POSIX")
        let dayFormat = DateFormatter()
        dayFormat.locale = posix
        dayFormat.dateFormat = "EEE MMM dd yyyy"
        let timeFormat = DateFormatter()
        timeFormat.locale = posix
        timeFormat.dateFormat = "h:mm a"
        let stamp = DateFormatter()
        stamp.locale = posix
        stamp.dateFormat = "M/d/yyyy, h:mm:ss a"

        var text = "# Calendar Events for \(dayFormat.string(from: day))\n\n"
        if meetings.isEmpty {
            text += "\n\n#### No meetings today!\n"
        } else {
            for meeting in meetings {
                let title = cleanTitle(meeting.title)
                let link = noteNames.contains(title)
                    ? "[[\(title)]]"
                    : "[[\(newMeetingsFolder)/\(title)|\(title)]]"
                text += "\(timeFormat.string(from: meeting.start))"
                text += "- \(timeFormat.string(from: meeting.end))   "
                text += "**\(link)**  \n\n"
            }
        }
        text += "\n\n<p align=\"right\">Generated on \(stamp.string(from: generatedAt))</p>\n"
        text += "\n<p align=\"right\">Generated by ObsidianAgenda</p>\n"
        return text
    }

    /// obsidian:// URL that opens the meeting's note (or creates it in the meetings folder).
    public static func openURL(vaultName: String, meetingTitle: String, noteNames: Set<String>,
                               newMeetingsFolder: String) -> URL? {
        let title = cleanTitle(meetingTitle)
        var components = URLComponents()
        components.scheme = "obsidian"
        if noteNames.contains(title) {
            components.host = "open"
            components.queryItems = [.init(name: "vault", value: vaultName), .init(name: "file", value: title)]
        } else {
            components.host = "new"
            components.queryItems = [.init(name: "vault", value: vaultName),
                                     .init(name: "file", value: "\(newMeetingsFolder)/\(title)")]
        }
        return components.url
    }
}
